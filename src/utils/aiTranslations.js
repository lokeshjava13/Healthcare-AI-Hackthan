export function getReportTranslations(language) {
  return reportTranslations[language] || reportTranslations.en
}

export function localizeReportResult(result, translations) {
  if (!result) return null
  const flagged = result.findings.some((finding) => ['low', 'high'].includes(finding.status))
  const summaryKey = result.summaryKey
    || (result.findings.some((finding) => finding.name === 'Hemoglobin' && finding.status === 'low')
      ? 'lowHemoglobin'
      : flagged ? 'flagged' : 'review')
  const recommendationKey = result.recommendationKey || (summaryKey === 'lowHemoglobin' ? 'lowHemoglobin' : 'review')
  return {
    ...result,
    summary: translations.summary[summaryKey],
    recommendations: translations.recommendation[recommendationKey],
    disclaimer: translations.disclaimer,
    findings: result.findings.map((finding) => ({
      ...finding,
      localizedName: translations.findingNames[finding.name] || finding.name,
      localizedReference: translations.references[finding.name] || finding.reference,
      localizedStatus: finding.status === 'context'
        ? translations.context
        : finding.status === 'demo-normal' ? translations.demoNormal : translations[finding.status] || finding.status,
    })),
    localizedRiskLevel: translations.riskLevel[result.riskLevel] || result.riskLevel,
  }
}
