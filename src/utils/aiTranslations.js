export function getSymptomResultCopy(key, duration, language) {
  const translation = symptomTranslations[language] || symptomTranslations.en
  const entry = translation[key] || translation.other
  const urgency = entry.urgency || (duration === '1 week' ? 'Medium' : 'Low')
  const urgencyMessage = entry.urgencyMessage
    || (duration === '1 week' ? entry.long : entry.short)
  const specialistQueries = {
    cold: 'General Physician',
    dizziness: 'Neurology',
    emergency: 'Emergency department',
    other: 'General Physician',
    stomach: 'Gastroenterology',
    viral: 'General Physician',
  }

  return {
    ...entry,
    urgency,
    urgencyMessage,
    specialistQuery: specialistQueries[key] || specialistQueries.other,
    labels: translation.labels,
    urgencyLabel: translation.labels.urgency[urgency],
  }
}

